// Writes dist/sw.js after `expo export -p web`.
//
// The service worker stores every file of the web build on the device the
// first time the site is opened, so the web version (including when saved to
// an iPhone home screen) opens and works with no signal afterwards.

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const dist = path.join(__dirname, '..', 'dist');

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const full = path.join(dir, e.name);
    return e.isDirectory() ? walk(full) : [full];
  });
}

const files = walk(dist)
  .map((f) => '/' + path.relative(dist, f).split(path.sep).join('/'))
  .filter((f) => f !== '/sw.js' && !f.endsWith('.map'))
  .sort();

// Library fonts the app actually uses. Other bundled icon sets / font weights
// are left out of the up-front download (they're cached if ever requested).
const USED_LIBRARY_ASSETS = /(Inter_(400Regular|500Medium|600SemiBold|700Bold)|Ionicons)\.[0-9a-f]+\.ttf$/;
const precache = files.filter((f) => !f.startsWith('/assets/node_modules/') || USED_LIBRARY_ASSETS.test(f));

const hash = crypto.createHash('sha256');
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(dist, f)));
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/build-sw.js — do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = 'hour-keeper-' + VERSION;
const PRECACHE = ${JSON.stringify(['/', ...precache], null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('hour-keeper-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Only the app's own files. Data requests (Supabase) go straight to the network;
  // the app keeps its own offline copy of the data.
  if (url.origin !== self.location.origin) return;

  // Page loads (any route — /job/123, /admin …): try the network briefly for
  // the newest version, otherwise open the saved app.
  if (req.mode === 'navigate') {
    event.respondWith(
      Promise.race([
        fetch(req).then((res) => (res.ok ? res : Promise.reject(res))),
        new Promise((_, reject) => setTimeout(reject, 3000)),
      ]).catch(() => caches.match('/index.html', { cacheName: CACHE })),
    );
    return;
  }

  event.respondWith(
    caches.match(req, { cacheName: CACHE }).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && res.type === 'basic') {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;

fs.writeFileSync(path.join(dist, 'sw.js'), sw);
console.log(`sw.js: ${precache.length} of ${files.length} files precached (version ${version})`);
